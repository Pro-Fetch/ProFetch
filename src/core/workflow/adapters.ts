/**
 * Host adapter rendering — the single source for the files in `adapters/`.
 *
 * Kept separate from the generator script so a test can render the same bytes and compare them with
 * what is on disk. Adapters that are copied by hand drift from the instruction the server actually
 * serves, and a stale instruction is worse than none: it tells the host to call actions that no
 * longer exist.
 */

import { ENFORCED, HOST_INSTRUCTION, NOT_GUARANTEED } from '../../tools/workflow/workflow.js';

export interface HostAdapter {
  file: string;
  title: string;
  where: string;
}

export const HOSTS: readonly HostAdapter[] = [
  {
    file: 'claude-code.md',
    title: 'Claude Code',
    where: 'Paste into `CLAUDE.md` at the project root (or `~/.claude/CLAUDE.md` for every project).',
  },
  { file: 'codex.md', title: 'Codex CLI', where: 'Paste into `AGENTS.md` at the project root.' },
  { file: 'gemini-cli.md', title: 'Gemini CLI', where: 'Paste into `GEMINI.md` at the project root.' },
  { file: 'copilot-cli.md', title: 'GitHub Copilot CLI', where: 'Paste into `.github/copilot-instructions.md`.' },
  {
    file: 'openclaw.md',
    title: 'OpenClaw / other MCP clients',
    where:
      'Put the block into whatever per-project instruction file the client reads; if it has none, paste it at the start of each session.',
  },
];

const CONFIG = [
  '```json',
  '{',
  '  "mcpServers": {',
  '    "pro-fetch": {',
  '      "command": "npx",',
  '      "args": ["-y", "@pro-fetch/mcp"],',
  '      "env": { "PRO_FETCH_PROFILE": "smart" }',
  '    }',
  '  }',
  '}',
  '```',
].join(String.fromCharCode(10));

const lines = (items: readonly string[]): string => items.map((item) => `- ${item}`).join(String.fromCharCode(10));

export function renderAdapter(host: HostAdapter): string {
  return [
    `# Pro-Fetch adapter — ${host.title}`,
    '',
    host.where,
    '',
    '```text',
    HOST_INSTRUCTION,
    '```',
    '',
    '## MCP connection',
    '',
    CONFIG,
    '',
    '## What the server enforces',
    '',
    lines(ENFORCED),
    '',
    '## What it cannot guarantee (§15.4)',
    '',
    lines(NOT_GUARANTEED),
    '',
    'Generated by `scripts/gen-adapters.mts` — do not edit by hand; run `npm run gen:adapters`.',
    '',
  ].join(String.fromCharCode(10));
}

export function renderReadme(): string {
  return [
    '# Host adapters',
    '',
    'Pro-Fetch is an MCP server: it advertises tools and refuses illegal moves. It cannot make the',
    'connected model think in a certain way (spec §15.4), so running the MexaPlan → SmartToDo →',
    'MaxEffort cycle on substantial work depends on an instruction the host chooses to carry. These',
    'files are that instruction, per host.',
    '',
    'Every file below is generated from `HOST_INSTRUCTION` in `src/tools/workflow/workflow.ts` — the',
    'same text `pro_fetch_workflow {action:"introduce"}` returns. Change it there and run',
    '`npm run gen:adapters`; a test fails if a file drifts from the source.',
    '',
    '| Host | File |',
    '|---|---|',
    ...HOSTS.map((host) => `| ${host.title} | [adapters/${host.file}](./${host.file}) |`),
    '',
    '## What an adapter has to do (§15.2)',
    '',
    lines([
      'configure the MCP connection;',
      'install the instruction block above (or a skill carrying it);',
      'open a separate agent/session for the audit when the host can, so the review is independent',
      '  rather than the same context grading its own plan;',
      "use the host's own model and credentials — Pro-Fetch never asks for a separate LLM API key;",
      "map the host's file/terminal/patch abilities onto the tools it exposes;",
      'verify the workflow actually ran: `pro_fetch_workflow {action:"introduce"}` must answer, and a',
      '  finished job must be reachable through `status`.',
    ]),
    '',
    '## The honest limit',
    '',
    'A client that only allows connecting an MCP server, with no way to carry an instruction, cannot be',
    'made to run the three phases automatically. In that case the gates still hold for every call the',
    'host does make through the workflow — nothing can be marked complete without evidence — but the',
    'automatic cycle is not guaranteed, and this repo does not claim it is.',
    '',
  ].join(String.fromCharCode(10));
}
